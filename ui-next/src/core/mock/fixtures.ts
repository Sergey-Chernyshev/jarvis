const makeVm = (
  id: string,
  project: string,
  state: VirtualMachine['state'],
  overrides: Partial<VirtualMachine> = {},
): VirtualMachine => {
  const base: VirtualMachine = {
    id,
    projectId: project,
    project,
    name: `${project}-${id.slice(-6)}`,
    state,
    busy: state === 'running',
    cpus: 4,
    ramUsed: state === 'running' ? 2.7 : 0,
    ramTotal: 4,
    diskUsed: project === 'jarvis' ? 10.2 : 4.8,
    diskMax: 120,
    autostart: project === 'jarvis',
    mounts: [
    {
      id: `${id}-project`,
      host: `~/${project}`,
      guest: `/workspace/${project}`,
      mode: 'rw',
      description: 'Файлы проекта общие в обе стороны',
      removable: false,
    },
    {
      id: `${id}-docs`,
      host: '~/Documents/reference',
      guest: '/mnt/reference',
      mode: 'ro',
      description: 'Дополнительные материалы',
      removable: true,
    },
  ],
    home: homeTree,
    ...(state === 'running' ? { uptime: '2 ч 41 мин' } : {}),
  };
  return { ...base, ...overrides };
};

